    /// <summary>Interpolated critical value. alpha: 0.10, 0.05 or 0.01.</summary>
    public static double Lookup(GammaGofTest test, double alpha, int n, double k)
    {
        double[] table = (test, alpha) switch
        {
            (GammaGofTest.AndersonDarling, 0.10) => AD010,
            (GammaGofTest.KolmogorovSmirnov, 0.10) => KS010,
            (GammaGofTest.AndersonDarling, 0.05) => AD005,
            (GammaGofTest.KolmogorovSmirnov, 0.05) => KS005,
            (GammaGofTest.AndersonDarling, 0.01) => AD001,
            (GammaGofTest.KolmogorovSmirnov, 0.01) => KS001,
            _ => throw new ArgumentOutOfRangeException(nameof(alpha), "supported significance levels: 0.10, 0.05, 0.01"),
        };

        double nn = Math.Clamp(n, NRows[0], NRows[^1]);
        double kk = Math.Clamp(k, KColumns[0], KColumns[^1]);

        int i0 = UpperBound(NRows, nn) - 1;
        int j0 = UpperBound(KColumns, kk) - 1;
        int i1 = Math.Min(i0 + 1, NRows.Length - 1);
        int j1 = Math.Min(j0 + 1, KColumns.Length - 1);

        double tn = NRows[i1] == NRows[i0] ? 0 : (nn - NRows[i0]) / (NRows[i1] - NRows[i0]);
        double tk = KColumns[j1] == KColumns[j0] ? 0
            : Math.Log(kk / KColumns[j0]) / Math.Log(KColumns[j1] / KColumns[j0]);

        double v00 = table[i0 * KColumns.Length + j0];
        double v01 = table[i0 * KColumns.Length + j1];
        double v10 = table[i1 * KColumns.Length + j0];
        double v11 = table[i1 * KColumns.Length + j1];

        return (1 - tn) * ((1 - tk) * v00 + tk * v01) + tn * ((1 - tk) * v10 + tk * v11);
    }

    // Index of the first element strictly greater than value (binary search).
    private static int UpperBound(int[] sorted, double value)
    {
        int lo = 0, hi = sorted.Length;
        while (lo < hi)
        {
            int mid = (lo + hi) / 2;
            if (sorted[mid] <= value) lo = mid + 1;
            else hi = mid;
        }
        return Math.Max(lo, 1);
    }

